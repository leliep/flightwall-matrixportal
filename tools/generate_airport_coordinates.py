#!/usr/bin/env python3
import json
from pathlib import Path


root = Path(__file__).resolve().parents[1]
coordinates = json.loads(
    (root / "data/airport_coordinates.json").read_text(encoding="utf-8")
)
rows = []
for code, position in sorted(coordinates.items()):
    latitude = round(float(position["latitude"]) * 1_000_000)
    longitude = round(float(position["longitude"]) * 1_000_000)
    elevation = position["elevation_ft"]
    elevation = -32768 if elevation is None else int(elevation)
    rows.append(f'  {{"{code}", {latitude}, {longitude}, {elevation}}},')

output = """// Generated by tools/generate_airport_coordinates.py; do not edit manually.
#include "AirportCoordinates.hpp"

namespace {
struct AirportCoordinateRow {
  const char* code;
  int32_t latitudeE6;
  int32_t longitudeE6;
  int16_t elevationFt;
};
const AirportCoordinateRow coordinates[] = {
""" + "\n".join(rows) + """
};
}  // namespace

bool airportCoordinates(const String& code, AirportCoordinates& result) {
  int low = 0;
  int high = static_cast<int>(sizeof(coordinates) / sizeof(coordinates[0])) - 1;
  while (low <= high) {
    const int middle = low + (high - low) / 2;
    const int comparison = code.compareTo(coordinates[middle].code);
    if (comparison == 0) {
      result.latitude = coordinates[middle].latitudeE6 / 1000000.0;
      result.longitude = coordinates[middle].longitudeE6 / 1000000.0;
      result.elevationFt = coordinates[middle].elevationFt;
      result.hasElevation = coordinates[middle].elevationFt != -32768;
      return true;
    }
    if (comparison < 0) high = middle - 1;
    else low = middle + 1;
  }
  result = {};
  return false;
}
"""
(root / "src/AirportCoordinates.generated.cpp").write_text(output, encoding="utf-8")
