#!/usr/bin/env python3
"""Generate the small local type-name fallback table (no runtime service)."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
names=json.loads((root/'data/aircraft_type_names.json').read_text())
rows=['  {'+json.dumps(code)+', '+json.dumps(name,ensure_ascii=False)+'},' for code,name in sorted(names.items())]
output='''// Generated by tools/generate_aircraft_type_names.py; do not edit manually.
#include "AircraftTypeNames.hpp"
namespace {
struct AircraftTypeName { const char *code; const char *name; };
const AircraftTypeName names[] = {
'''+ '\n'.join(rows)+'''
};
}
String aircraftTypeDisplayName(const String &code) {
  int low=0;
  int high=static_cast<int>(sizeof(names)/sizeof(names[0]))-1;
  while (low<=high) {
    const int middle=low+(high-low)/2;
    const int comparison=code.compareTo(names[middle].code);
    if (comparison==0) return names[middle].name;
    if (comparison<0) high=middle-1;
    else low=middle+1;
  }
  return "";
}
'''
(root/'src/AircraftTypeNames.generated.cpp').write_text(output)
