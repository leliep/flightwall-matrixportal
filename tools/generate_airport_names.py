#!/usr/bin/env python3
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
names = json.loads((root / "data/airport_names.de.json").read_text())
rows = []
for code, name in sorted(names.items()):
    escaped = name.replace("\\", "\\\\").replace('"', '\\"')
    rows.append(f'  {{"{code}", "{escaped}"}},')

output = """// Generated by tools/generate_airport_names.py; do not edit manually.
#include "AirportNames.hpp"

namespace {
struct AirportName { const char* code; const char* name; };
const AirportName names[] = {
""" + "\n".join(rows) + """
};
}  // namespace

String airportDisplayName(const String& code) {
  int low = 0;
  int high = static_cast<int>(sizeof(names) / sizeof(names[0])) - 1;
  while (low <= high) {
    const int middle = low + (high - low) / 2;
    const int comparison = code.compareTo(names[middle].code);
    if (comparison == 0) return names[middle].name;
    if (comparison < 0) high = middle - 1;
    else low = middle + 1;
  }
  return "";
}
"""
(root / "src/AirportNames.generated.cpp").write_text(output)
